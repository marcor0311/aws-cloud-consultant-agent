"""Dependencies injected by composition, not constructed by the business service."""

from typing import Protocol


class OpeningRepository(Protocol):
    def reserve(self, request): ...
    def get(self, case_id): ...
    def queue(self): ...
    def update(self, case_id, **changes): ...
    def lock(self, key): ...
    def work(self, case_id): ...
    def deliver(self, record): ...
    def preparation_delivery(self, case_id, files): ...
    def accept_preparation(self, record, source): ...
    def validate_preparation(self, record): ...
    def accept_board(self, case_id, certificate): ...
    def audit(self, case_id): ...


class ProjectGitHub(Protocol):
    def ensure_repository(self, record): ...
    def publish(self, record, files): ...
    def merge_initial_structure(self, record): ...
    def assign_architecture(self, record, issue_body, template): ...
