"""Storage operations needed by OTP rules, with plain data at the boundary."""

from contextlib import AbstractContextManager
from typing import Protocol


class VerificationTransaction(Protocol):
    def get(self, session_id: str) -> dict | None: ...
    def revoke(self, session_id: str) -> None: ...
    def create_session(
        self, session_id: str, origin_id: str, email: str, client_code: str
    ) -> None: ...
    def change_identity(
        self, email: str, client_code: str, session_id: str
    ) -> None: ...
    def prune_events(self, cutoff: float) -> None: ...
    def latest_send(self, email: str, session_id: str) -> float | None: ...
    def recent_events(
        self, kind: str, cutoff: float, email: str, origin_id: str
    ) -> list[dict]: ...
    def save_challenge(
        self, challenge_id: str, digest: str, expires: float, session_id: str
    ) -> None: ...
    def record_event(
        self, email: str, origin_id: str, session_id: str, kind: str, now: float
    ) -> None: ...
    def cancel_sending(self, session_id: str, challenge_id: str) -> None: ...
    def confirm_sent(self, session_id: str, challenge_id: str) -> int: ...
    def expire(self, session_id: str) -> None: ...
    def set_attempts(self, attempts: int, state: str, session_id: str) -> None: ...
    def mark_verified(self, until: float, session_id: str) -> None: ...
    def close(self, session_id: str) -> None: ...


class VerificationRepository(Protocol):
    def get(self, session_id: str) -> dict | None: ...
    def transaction(self) -> AbstractContextManager[VerificationTransaction]: ...
